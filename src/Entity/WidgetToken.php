<?php

declare(strict_types=1);

namespace App\Entity;

use App\Repository\WidgetTokenRepository;
use Doctrine\ORM\Mapping as ORM;

use function Symfony\Component\Clock\now;

/**
 * What the widget of a project holds, on one site and in one browser,
 * once a user linked their account there: it signs the requests of the
 * widget in their name, on the project of that site only, for a month.
 * Only the SHA-256 of the secret is kept. A token belongs to its user and
 * to the site it was given for: it goes with either (the database removes
 * it with its site), and is deleted, not revoked.
 */
#[ORM\Entity(repositoryClass: WidgetTokenRepository::class)]
#[ORM\UniqueConstraint(name: 'uniq_widget_token_hash', columns: ['hash'])]
class WidgetToken
{
    public const string PREFIX = 'cairnw_';
    public const string PATTERN = '/^cairnw_[0-9a-f]{64}$/';

    /** How long a browser stays linked. */
    public const string LIFETIME = '+30 days';

    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column]
    private ?int $id = null;

    #[ORM\ManyToOne]
    #[ORM\JoinColumn(nullable: false)]
    private User $user;

    #[ORM\ManyToOne]
    #[ORM\JoinColumn(nullable: false, onDelete: 'CASCADE')]
    private WidgetSite $site;

    #[ORM\Column(length: 64)]
    private string $hash;

    #[ORM\Column]
    private \DateTimeImmutable $createdAt;

    #[ORM\Column]
    private \DateTimeImmutable $expiresAt;

    /**
     * @param string $secret the secret generated by newSecret(), which the caller hands to the widget
     */
    public function __construct(User $user, WidgetSite $site, #[\SensitiveParameter] string $secret)
    {
        $this->user = $user;
        $this->site = $site;
        $this->hash = self::hash($secret);
        $this->createdAt = now();
        $this->expiresAt = $this->createdAt->modify(self::LIFETIME);
    }

    public static function newSecret(): string
    {
        return self::PREFIX.bin2hex(random_bytes(32));
    }

    /**
     * The secrets are long random strings: a plain SHA-256 is enough, and
     * lets the token be found by its hash.
     */
    public static function hash(#[\SensitiveParameter] string $secret): string
    {
        return hash('sha256', $secret);
    }

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getUser(): User
    {
        return $this->user;
    }

    public function getSite(): WidgetSite
    {
        return $this->site;
    }

    public function getCreatedAt(): \DateTimeImmutable
    {
        return $this->createdAt;
    }

    public function getExpiresAt(): \DateTimeImmutable
    {
        return $this->expiresAt;
    }

    public function isExpired(\DateTimeImmutable $now): bool
    {
        return $this->expiresAt <= $now;
    }
}
